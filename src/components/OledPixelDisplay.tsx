export function OledPixelDisplay({ pattern, className = '' }: OledPixelDisplayProps) {
  const rows = BITMAPS[pattern] || BITMAPS.smiley;
  const cols = rows[0]?.length || 24;
  const cellSize = 6;
  const gap = 1;
  const topOffset = 18;
  const svgW = cols * (cellSize + gap) + 16;
  const svgH = rows.length * (cellSize + gap) + topOffset + 10;

  return (
    <svg
      viewBox={`0 0 ${svgW} ${svgH}`}
      role="img"
      aria-label={`Tampilan grafis piksel OLED mode ${pattern}`}
      className={`w-full h-auto block ${className}`}
    >
      {/* Dual-zone yellow indicator strip at top (characteristic SSD1306 0.96" OLED band) */}
      <g fill="#FACC15">
        <rect x="10" y="6" width="5" height="5" />
        <rect x="18" y="6" width="5" height="5" />
        <rect x="26" y="6" width="5" height="5" />
        <rect x={svgW - 28} y="6" width="18" height="5" />
        <rect x={svgW - 40} y="6" width="8" height="5" opacity="0.55" />
      </g>
      {/* Active cyan pixel matrix (zero text inside display) */}
      <g fill="#38BDF8">
        {rows.map((row, y) =>
          Array.from(row).map((bit, x) =>
            bit === '1' ? (
              <rect
                key={`${x}-${y}`}
                x={8 + x * (cellSize + gap)}
                y={topOffset + y * (cellSize + gap)}
                width={cellSize}
                height={cellSize}
              />
            ) : null
          )
        )}
      </g>
    </svg>
  );
}
